//! Разбор кадра из недоверенных байт.
//!
//! Кадр приезжает из шифрованного канала, но «шифрованный» не значит
//! «доверенный»: сессию открывает кто угодно, у кого есть свой ключ, и
//! дальше он волен слать что угодно. Паника здесь — это падение
//! соединения в лучшем случае и падение процесса в худшем.

#![no_main]

use libfuzzer_sys::fuzz_target;
use trust_message_tcp::net::framing::decode_frame;

fuzz_target!(|data: &[u8]| {
    // Интересует только отсутствие паники: ошибка разбора — штатный
    // результат, соединение на ней закрывается.
    let _ = decode_frame(data);
});
