//! Сборка логических кадров из потока чанков.
//!
//! Единственный самописный парсер транспорта: Noise-сообщение ограничено
//! 65535 байтами, а кадр протокола — восемью мегабайтами, поэтому внутри
//! канала живёт собственный заголовок длины. Проверяется не только
//! отсутствие паники, но и то, ради чего этот код существует: сколько бы
//! мусора ни прислал пир, буфер остаётся ограниченным.

#![no_main]

use libfuzzer_sys::fuzz_target;
use trust_message_tcp::net::noise::FrameAssembler;

/// Небольшой потолок: он делает интересные случаи (заявленная длина рядом
/// с границей) достижимыми за разумное число байт от фаззера.
const MAX_FRAME_LEN: usize = 4096;
/// Потолок одного Noise-сообщения — столько максимум приезжает за раз.
const MAX_CHUNK: usize = 65535;

fuzz_target!(|data: &[u8]| {
    let mut assembler = FrameAssembler::new(MAX_FRAME_LEN);

    // Первый байт задаёт размер чанка: так фаззер управляет тем, как поток
    // рвётся на куски, а не только его содержимым. Ровно это и ломает
    // наивные сборщики — заголовок, приехавший по одному байту.
    let Some((&chunk_hint, body)) = data.split_first() else {
        return;
    };
    let chunk_size = 1 + usize::from(chunk_hint);

    for chunk in body.chunks(chunk_size) {
        assembler.push(chunk);

        // Драйвим так же, как это делает `next_frame`: после каждого чанка
        // вычерпываем все собравшиеся кадры.
        loop {
            match assembler.take_frame() {
                Ok(Some(frame)) => {
                    assert!(
                        frame.len() <= MAX_FRAME_LEN,
                        "собранный кадр больше потолка"
                    );
                }
                Ok(None) => break,
                // Заявленная длина больше потолка — соединение закрывается,
                // дальше разбирать нечего.
                Err(_) => return,
            }
        }

        // Инвариант, ради которого тип и выделен: неполный кадр не может
        // раздуть буфер сверх одного кадра плюс последний чанк.
        assert!(
            assembler.buffered() <= MAX_FRAME_LEN + 4 + MAX_CHUNK,
            "буфер вырос сверх одного кадра: {}",
            assembler.buffered()
        );
    }
});
